import assert from 'node:assert/strict';
import {createCameraMotionTracker} from '../src/performance/camera-motion.js';
const camera=height=>({positionWC:{x:6378137+height,y:0,z:0},directionWC:{x:-1,y:0,z:0},upWC:{x:0,y:0,z:1},
 positionCartographic:{height},nativeMoving:true});
const cam=camera(10000000),original=structuredClone(cam),tracker=createCameraMotionTracker();
assert.equal(tracker.update(cam,0),true);
assert.equal(tracker.update(cam,801),false,'A stationary pose must settle even when a native movement flag is stuck');
assert.deepEqual(cam,original,'Reading motion must not change the renderer camera');
cam.positionWC.y=1;cam.directionWC.y=1e-8;
assert.equal(tracker.update(cam,1000),false,'Subpixel orbital numerical jitter must not restart motion quality');
cam.positionWC.y=12;
assert.equal(tracker.update(cam,1100),true,'Actual translation must restart motion immediately');
cam.positionWC.y=13;
assert.equal(tracker.update(cam,1901),false,'Small changes after a real move must settle');
cam.positionWC.y=24;
assert.equal(tracker.update(cam,2000),true,'Small cumulative movements must be measured against the last significant pose');
assert.equal(tracker.update(cam,2801),false);
cam.directionWC.y=1e-4;
assert.equal(tracker.update(cam,2900),true,'Rotation without translation must count as movement');
assert.equal(tracker.update(cam,3701),false);
cam.upWC.y=1e-4;
assert.equal(tracker.update(cam,3800),true,'Camera roll must count as movement');
assert.equal(tracker.update(cam,4601),false);
assert.equal(tracker.update(cam,5),true,'Clock resets must restart the settling window');
assert.equal(tracker.update(cam,806),false);
const near=camera(1000),close=createCameraMotionTracker();
assert.equal(close.update(near,0),true);assert.equal(close.update(near,801),false);
near.positionWC.y=.02;
assert.equal(close.update(near,900),true,'Centimetre-scale nearby movement must not use the orbital tolerance');
assert.equal(close.update({...near,positionWC:{x:NaN,y:0,z:0}},1000),true,'Invalid samples must conservatively retain motion quality');
assert.ok(Object.values(close.details()).every(Number.isFinite),'Diagnostics must remain finite after an invalid sample');
assert.equal(close.update(near,1901),false,'A recovered stable pose must settle again');
console.log('PASS: pose-based idle recovery, orbital jitter, cumulative and nearby translation, pan/roll, clock reset and invalid-sample recovery');
