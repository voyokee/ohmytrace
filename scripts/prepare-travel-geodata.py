"""Build compact offline lookup supplements.
Usage: python3 scripts/prepare-travel-geodata.py countries10m.geojson airports.csv
Natural Earth v5.1.2 + OurAirports public-domain snapshots; see data/SOURCES.md.
Reads the existing city packs so translations remain identical. No network at build/runtime.
"""
import csv, hashlib, json, pathlib, sys
root=pathlib.Path(__file__).resolve().parents[1]; out=root/'src/life/geocoding/data'
def write(name,data): (out/name).write_text(json.dumps(data,ensure_ascii=False,separators=(',',':'))+'\n')
cities=[]
for country in json.loads((out/'index.json').read_text())['countries']:
 pack=json.loads((out/(country['code']+'.json')).read_text())
 for c in pack['cities']:
  cities.append([country['code'],c['name'],round(c['coordinates']['latitude'],5),round(c['coordinates']['longitude'],5),c.get('admin')])
write('city-index.json',cities)
features=json.loads(pathlib.Path(sys.argv[1]).read_text())['features']
# Preserve original 10m vertices for small city regions; mainland uses the city-first rule.
regions={f['properties']['ADM0_A3']:f['geometry'] for f in features if f['properties']['ADM0_A3'] in ['HKG','MAC','SGP']}
write('city-regions.json',regions)
airports=[]
for a in csv.DictReader(pathlib.Path(sys.argv[2]).open()):
 if a['type']=='large_airport' and a['scheduled_service']=='yes':
  airports.append([a['ident'],a['iata_code'] or a['ident'],round(float(a['latitude_deg']),5),round(float(a['longitude_deg']),5)])
(root/'src/life/media/airports.js').write_text('// OurAirports public domain; generated by scripts/prepare-travel-geodata.py.\nexport const AIRPORTS='+json.dumps(sorted(airports),separators=(',',':'))+';\n')
write('travel-data-sources.json',{'naturalEarth':'v5.1.2/ne_10m_admin_0_countries.geojson','naturalEarthSha256':hashlib.sha256(pathlib.Path(sys.argv[1]).read_bytes()).hexdigest(),'ourAirports':'https://davidmegginson.github.io/ourairports-data/airports.csv','ourAirportsSha256':hashlib.sha256(pathlib.Path(sys.argv[2]).read_bytes()).hexdigest(),'airportFilter':'type=large_airport AND scheduled_service=yes','airportCount':len(airports),'license':'Public Domain'})
print(len(cities),'city points;',len(airports),'airports;',sum((out/n).stat().st_size for n in ['city-index.json','city-regions.json']),'lookup bytes')
