export function normalizeRegion(result){
 if(!result||!result.countryCode&&!result.country)return result;
 const r=regionOf(result.countryCode||result.country,result.admin1),admin1=r.code==='IND'&&r.sovereignCode==='CHN'?'西藏自治区（藏南地区）':r.code==='KOS'?'科索沃地区':result.admin1;
 return {...result,country:r.displayName,sovereignCode:r.sovereignCode,admin1,
  displayName:[r.displayName,admin1,result.city?(result.precision==='provider-result'?result.city:'附近城市：'+result.city):null].filter(Boolean).join(' / ')};
}
