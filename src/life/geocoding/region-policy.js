export function photoPlaceName(place,data){
 const city=place.location?.photoCity;if(!city||city.hasCity!==false&&place.name!==city.country)return place.name;
 if(data?.evidence.some(e=>e.state==='manual'&&place.evidenceIds?.includes(e.id)))return place.name;
 const r=normalizeRegion({country:city.country,countryCode:city.countryCode,admin1:city.region});
 return place.name===city.country?r.country:place.name===city.region?r.admin1:regionOf(place.name).displayName;
}
