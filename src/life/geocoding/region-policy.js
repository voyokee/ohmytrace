export function regionOf(input,admin1=null){
 const text=String(input??'').trim(),upper=text.toUpperCase(),code=byCode.has(upper)?upper:byName.get(upper)||byName.get(text)||upper;
 const row=byCode.get(code),override=code==='IND'&&['阿鲁纳恰尔邦','Arunachal Pradesh','西藏自治区（藏南地区）'].includes(admin1)?['中国','CHN','province']:policy[code];
 const [displayName,sovereignCode,kind]=override||[row?.name||text,code||null,'country'];
 return {code,displayName,shortName:displayName,sovereignCode,kind};
}
